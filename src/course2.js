async function seedWeeks(q) {
  for (const [num, items] of Object.entries(WEEKS2_8)) {
    const w = (await q('SELECT id FROM weeks WHERE number = $1', [parseInt(num, 10)])).rows[0];
    if (!w) continue;
    const c = (await q('SELECT count(*)::int AS n FROM items WHERE week_id = $1', [w.id])).rows[0].n;
    if (c > 0) continue;
    let pos = 1;
    for (const [kind, title, body] of items) {
      const staffOnly = kind === 'note';
      const realKind = kind === 'note' ? 'note' : kind;
      await q('INSERT INTO items (week_id, position, kind, title, body, staff_only) VALUES ($1,$2,$3,$4,$5,$6)',
        [w.id, pos++, realKind, title, body, staffOnly]);
    }
  }
}

module.exports = { seedWeeks };
